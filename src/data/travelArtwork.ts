export function getCountryPhotoUrl(countryCode: string, continent?: string): string {
  const upper = (countryCode || 'JP').toUpperCase();
  if (COUNTRY_PHOTO_MAP[upper]) {
    return COUNTRY_PHOTO_MAP[upper];
  }
  const pool =
    (continent && CONTINENT_FALLBACK_POOL[continent]) || CONTINENT_FALLBACK_POOL.Europe;
  const hash = upper.charCodeAt(0) * 31 + (upper.charCodeAt(1) || 0);
  return pool[hash % pool.length];
}
